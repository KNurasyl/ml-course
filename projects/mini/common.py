"""Shared helpers of the mini-projects MP1-MP6 (REFACTORING_PLAN_2.0, section 6).

Data of the fictional company lives in data/company (generated by data/company/generate.py). The learner's work goes
to submissions/MPx/ (ignored by git). Every check.py prints what passed and what did not, in Russian, and exits with
1 while an acceptance criterion is not met. A check verifies structure and recomputes numbers; it does not grade the
learner and does not replace the tutor's questions (course/tutor-protocol.md).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COMPANY = ROOT / "data/company"
SUBMISSIONS = ROOT / "submissions"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def kb_documents(folder: Path = COMPANY / "kb") -> dict[str, dict]:
    """KB-xxx -> {"id", "title", "topic", "updated", "text"} from the front matter of each Markdown file."""
    docs = {}
    for path in sorted(Path(folder).glob("KB-*.md")):
        raw = path.read_text(encoding="utf-8")
        head, _, body = raw.partition("\n---\n")
        meta = dict(re.findall(r"(?m)^(\w+): (.*)$", head))
        docs[meta["id"]] = {"id": meta["id"], "title": meta["title"], "topic": meta["topic"], "updated": meta["updated"],
                            "text": body.strip()}
    return docs


def operator_requests() -> list[dict]:
    return read_jsonl(COMPANY / "operator_requests.jsonl")


def cohen_kappa(a: list, b: list) -> float:
    """Agreement of two labelings beyond chance; 1.0 when both are constant and equal."""
    if len(a) != len(b) or not a:
        raise ValueError("Two non-empty labelings of the same length are needed")
    labels = sorted(set(a) | set(b), key=str)
    n = len(a)
    observed = sum(x == y for x, y in zip(a, b)) / n
    expected = sum((a.count(label) / n) * (b.count(label) / n) for label in labels)
    return 1.0 if expected == 1 else (observed - expected) / (1 - expected)


class Report:
    """Collect criteria, print them and turn the result into an exit code."""

    def __init__(self, title: str):
        self.title, self.rows = title, []

    def check(self, ok: bool, text: str, detail: str = "") -> bool:
        self.rows.append((bool(ok), text, detail))
        return bool(ok)

    def finish(self) -> int:
        sys.stdout.reconfigure(encoding="utf-8")
        print(self.title)
        for ok, text, detail in self.rows:
            print(f"  [{'ok' if ok else '--'}] {text}" + (f" — {detail}" if detail else ""))
        passed = sum(ok for ok, *_ in self.rows)
        print(f"Критериев выполнено: {passed} из {len(self.rows)}.")
        if passed < len(self.rows):
            print("Проверка структуры не пройдена: исправь отмеченные пункты. Тьютор задаст вопросы по содержанию отдельно.")
        return 0 if passed == len(self.rows) else 1
