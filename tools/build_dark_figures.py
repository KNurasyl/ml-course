"""Dark copies of the hand-drawn lesson figures (phase 6, D4).

The extension lessons (X) carry SVG figures drawn by hand, without a generator, and the
reader shows them as images. This tool derives `<name>-dark.svg` next to each of them by
mapping every colour onto a 6.0 dark token (values read from tools/reader.css), with the
same roles as the generated figures:

- ink 182b3a, muted 526474, blue 245bba -> accent, teal 087e82 -> act, amber a65c12 -> hint;
- soft fills eef4fc / edf8f7 / fff3e5 -> accent-soft / act-soft / hint-soft;
- tints of a hue (light blue 9fb8e3, light teal 7cc4c6) -> that token at 55% opacity,
  so a secondary series stays apart from the full hue (author's decision, 10.11.2026);
- greys (author's decision): c9d1d9 bars -> muted, c9d1d9 lines -> line-strong; empty bar
  tracks eef1f4 / e4d6c6 / d9dee3 -> line; card f7f9fb -> surface;
- white -> paper, white text on a coloured fill -> bg.

An unknown colour stops the build: a new colour needs the author's decision. The light
files are only read; the reader picks the copy that matches the theme.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "course/assets"
SAME = {"#182b3a": "ink", "#526474": "muted", "#245bba": "accent", "#087e82": "act", "#a65c12": "hint",
        "#eef4fc": "accent-soft", "#edf8f7": "act-soft", "#fff3e5": "hint-soft",
        "#eef1f4": "line", "#e4d6c6": "line", "#d9dee3": "line", "#f7f9fb": "surface"}
TINTS = {"#9fb8e3": "accent", "#7cc4c6": "act"}
TINT_OPACITY = ".55"
COLOUR = re.compile(r'\s(fill|stroke)="(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3}|white|black)"')


def dark_tokens() -> dict[str, str]:
    css = (ROOT / "tools/reader.css").read_text(encoding="utf-8")
    block = re.search(r":root\{color-scheme:dark;(.*?)\}", css, re.DOTALL).group(1)
    return dict(re.findall(r"--([\w-]+):(#[0-9a-fA-F]{6})", block))


def hand_drawn(root: Path = ROOT) -> list[Path]:
    """Figures shown as images that no generator draws: course/assets SVGs outside the responsive mapping."""
    mapping = json.loads((root / "metadata/responsive-figures.json").read_text(encoding="utf-8"))
    return sorted(path for path in (root / "course/assets").glob("*.svg")
                  if path.relative_to(root).as_posix() not in mapping and not path.stem.endswith("-dark"))


def token_for(tag: str, prop: str, colour: str) -> tuple[str, str | None]:
    colour = colour.lower()
    if colour in ("white", "#fff", "#ffffff"):
        return ("bg" if tag == "text" else "paper"), None
    if colour == "#c9d1d9":
        return ("muted" if prop == "fill" else "line-strong"), None
    if colour in SAME:
        return SAME[colour], None
    if colour in TINTS:
        return TINTS[colour], TINT_OPACITY
    raise ValueError(colour)


def darken(svg: str, tokens: dict[str, str], name: str) -> str:
    unknown = set()

    def element(match: re.Match) -> str:
        tag, attributes, close = match.group(1), match.group(2), match.group(3)
        extra = []

        def colour(found: re.Match) -> str:
            prop, value = found.groups()
            try:
                token, opacity = token_for(tag, prop, value)
            except ValueError:
                unknown.add(value)
                return found.group(0)
            if opacity:
                extra.append(f' {prop}-opacity="{opacity}"')
            return f' {prop}="{tokens[token]}"'

        attributes = COLOUR.sub(colour, attributes)
        return f"<{tag}{attributes}{''.join(extra)}{close}>"

    dark = re.sub(r"<([a-zA-Z]+)(\s[^<>]*?)?(/?)>", lambda m: element(m) if m.group(2) else m.group(0), svg)
    if unknown:
        raise SystemExit(f"{name}: colours without a token, ask the author: {sorted(unknown)}")
    note = f"<!-- Dark copy of {name}, generated by tools/build_dark_figures.py (D4). Edit the light file. -->"
    return re.sub(r"(<svg\b[^>]*>)", lambda m: m.group(1) + note, dark, count=1)


def build(root: Path = ROOT) -> list[str]:
    tokens = dark_tokens()
    written = []
    for path in hand_drawn(root):
        target = path.with_name(f"{path.stem}-dark.svg")
        target.write_text(darken(path.read_text(encoding="utf-8"), tokens, path.name), encoding="utf-8", newline="\n")
        written.append(target.relative_to(root).as_posix())
    return written


if __name__ == "__main__":
    print(f"{len(build())} dark copies of hand-drawn figures written")
